// Package i18n 提供中/英文输出。语言来源: config.toml 的 lang 项 > $LANG 环境变量 > 中文。
// T() 以中文原文为 key, 英文表未收录时原样返回中文。
package i18n

import (
	"os"
	"strings"

	"github.com/BurntSushi/toml"

	"github.com/wubinstu/mihomo-cli/internal/app"
)

var lang = "zh"

func init() {
	var cfg struct {
		Lang string `toml:"cli_language"`
	}
	if data, err := os.ReadFile(app.SettingsFile); err == nil {
		_ = toml.Unmarshal(data, &cfg)
	}
	switch strings.ToLower(cfg.Lang) {
	case "zh", "en":
		lang = strings.ToLower(cfg.Lang)
	default:
		l := os.Getenv("LANG")
		switch {
		case strings.Contains(l, "zh"):
			lang = "zh"
		case l != "":
			lang = "en"
		}
	}
}

// Lang 当前语言 ("zh"/"en")
func Lang() string { return lang }

// Set 切换语言 (运行期)
func Set(l string) {
	switch strings.ToLower(l) {
	case "zh", "en":
		lang = strings.ToLower(l)
	}
}

// T 翻译: 英文模式下查表, 未收录/中文模式返回原文
func T(s string) string {
	if lang == "en" {
		if e, ok := en[s]; ok {
			return e
		}
	}
	return s
}

